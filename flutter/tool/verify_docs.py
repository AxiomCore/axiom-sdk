#!/usr/bin/env python3
"""Analyze every fenced ```dart block of the Flutter docs against this SDK.

Each block becomes one library in a scratch Flutter package that depends on
the axiom_flutter and axiom_flutter_auth sources of this repository and on a
client generated (by this repository's generator) from the contracts the
docs use. `dart analyze` then runs on the package; errors and warnings fail
the run and are reported at the doc file and line.

Blocks:
  * a block with `import` lines or top-level declarations is a whole file;
  * a block that ends in `;` or `}` is a list of statements, wrapped in an
    async function with a `BuildContext context` parameter;
  * any other block is an expression (a widget, for example).
Every library imports a shared prelude that declares the names docs use
without defining them (`sdk`, `auth`, `token`, `showMessage`, ...); a
declaration in the block itself wins over the prelude.

A block marked `<!-- verify: continued -->` (MDX: `{/* verify: continued */}`)
on one of the three lines above the fence is appended to the previous block
of the same page (a page that shows one file in two parts).

Opt out with `<!-- no-verify -->` (Markdown) or `{/* no-verify */}` (MDX), with
an optional reason after `no-verify`, on one of the three lines above the fence. Use it only for intentional
fragments, such as "before" code from other libraries.

Usage:
  flutter/tool/verify_docs.py                 # the four READMEs of this repo
  flutter/tool/verify_docs.py --public-docs <AxiomCore>/docs/content/docs
Options: --scratch <dir> (default: a temp dir), --keep, --axiom <cli path>.
Needs `flutter`/`dart` on PATH and, for --public-docs, the `axiom` CLI to
build tool/docs_contracts/*.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

FLUTTER = Path(__file__).resolve().parent.parent  # axiom-sdk/flutter
REPO = FLUTTER.parent

README_DOCS = [
    REPO / "README.md",
    FLUTTER / "axiom_flutter/README.md",
    FLUTTER / "axiom_flutter_generator/README.md",
    FLUTTER / "axiom_flutter_auth/README.md",
]
README_CONTRACTS = {
    "todos": FLUTTER / "axiom_flutter/example/assets/axiom/todos.axiom",
    "fixture": FLUTTER / "integration_app/assets/axiom/fixture.axiom",
}
PUBLIC_PAGES = [
    "getting-started/quickstart-flutter.mdx",
    "sdks/flutter.mdx",
    "sdks/flutter-auth.mdx",
    "guides/flutter-with-existing-backend.mdx",
    "guides/flutter-mock-first.mdx",
    "guides/migrate-from-dio-retrofit.mdx",
]
PUBLIC_CONTRACTS = ["tasks", "feed", "chat", "talks", "greetings"]

FENCE_RE = re.compile(r"^(\s*)```dart\b.*$")
OPT_OUT_RE = re.compile(r"<!--\s*no-verify\b[^>]*-->|\{/\*\s*no-verify\b.*?\*/\}")
CONTINUED_RE = re.compile(r"<!--\s*verify:\s*continued\s*-->|\{/\*\s*verify:\s*continued\s*\*/\}")

PRELUDE = """\
// Names the docs use without defining them. Generated by verify_docs.py.
// ignore_for_file: unused_element, unused_import
import 'package:axiom_flutter/axiom_flutter.dart';
import 'package:axiom_flutter_auth/axiom_flutter_auth.dart';
import 'package:flutter/material.dart';

import 'axiom_generated/axiom_sdk.dart';

export 'package:axiom_flutter/axiom_flutter.dart';
export 'package:axiom_flutter_auth/axiom_flutter_auth.dart';
export 'package:flutter/foundation.dart';
export 'package:flutter/material.dart';
export 'axiom_generated/axiom_sdk.dart';

late AxiomSdk sdk;
late final AxiomAuth auth;
String token = 'token';
String accessToken = 'token';
String email = 'ada@example.com';
String password = 'secret';
String code = '123456';
final dynamic myAuth = null;
void showMessage(String text) {}

class App extends StatelessWidget {
  const App({super.key});
  @override
  Widget build(BuildContext context) => const SizedBox();
}

class SignInPage extends StatelessWidget {
  const SignInPage({super.key, this.onSubmit});
  final Function? onSubmit;
  @override
  Widget build(BuildContext context) => const SizedBox();
}

class HomePage extends StatelessWidget {
  const HomePage({super.key, required this.subject});
  final String subject;
  @override
  Widget build(BuildContext context) => const SizedBox();
}
"""

HEADER = """\
// Generated by verify_docs.py from {src}:{line}
// ignore_for_file: unused_local_variable, unused_element, unused_import, avoid_print, dead_code, prefer_const_constructors, unnecessary_import, duplicate_import, depend_on_referenced_packages
import 'prelude.dart';
import 'axiom_generated/models.dart' as models;
"""

ANALYSIS_OPTIONS = """\
include: package:flutter_lints/flutter.yaml
linter:
  rules:
    avoid_print: false
"""


def extract_blocks(path):
    """Yield (start_line, code, continued) for each ```dart block not opted out."""
    lines = path.read_text().splitlines()
    i = 0
    while i < len(lines):
        m = FENCE_RE.match(lines[i])
        if not m:
            i += 1
            continue
        indent = m.group(1)
        start = i + 1
        opted_out = any(OPT_OUT_RE.search(l) for l in lines[max(0, i - 3):i])
        continued = any(CONTINUED_RE.search(l) for l in lines[max(0, i - 3):i])
        body = []
        i += 1
        while i < len(lines) and not lines[i].strip().startswith("```"):
            line = lines[i]
            body.append(line[len(indent):] if line.startswith(indent) else line.lstrip())
            i += 1
        i += 1
        if not opted_out:
            yield start + 1, "\n".join(body), continued


def is_whole_file(code):
    for line in code.splitlines():
        if line.startswith((" ", "\t", "//")) or not line.strip():
            continue
        if line.startswith("import ") or re.match(r"^(class|abstract|sealed|mixin|enum|extension|typedef|late) ", line):
            return True
        if re.match(r"^(Future|Stream|void|String|int|bool|Widget)\b[^=;]*\([^;]*\)\s*(async\s*)?(\{|=>)", line):
            return True
    return False


def wrap(code):
    """Return (dart source, number of lines before the block's first line)."""
    if is_whole_file(code):
        # The header imports the generated models as `models`; blank the
        # block's own copy of that import so line numbers stay aligned.
        body = []
        for line in code.splitlines():
            if line.startswith("import ") and "axiom_generated/models.dart" in line:
                body.append("")
            else:
                body.append(line)
        return "\n".join(body) + "\n", 0, "file"
    stripped = code.rstrip()
    if stripped.endswith(";") or stripped.endswith("}"):
        return ("Future<void> _snippet(BuildContext context) async {\n" + code + "\n}\n", 1, "statements")
    return ("Object _snippet(BuildContext context) => (\n" + code + "\n);\n", 1, "expression")


def run(cmd, cwd, **kw):
    return subprocess.run(cmd, cwd=cwd, text=True, capture_output=True, **kw)


def make_package(scratch, contracts):
    lib = scratch / "lib"
    lib.mkdir(parents=True, exist_ok=True)
    (scratch / "pubspec.yaml").write_text(f"""\
name: docs_snippets
publish_to: none
environment:
  sdk: ^3.8.0
dependencies:
  flutter:
    sdk: flutter
  axiom_flutter: ^0.150.0
  axiom_flutter_auth: ^0.150.0
dev_dependencies:
  flutter_lints: ^5.0.0
  axiom_flutter_generator: ^0.150.0
dependency_overrides:
  axiom_flutter:
    path: {FLUTTER / 'axiom_flutter'}
  axiom_flutter_auth:
    path: {FLUTTER / 'axiom_flutter_auth'}
  axiom_flutter_generator:
    path: {FLUTTER / 'axiom_flutter_generator'}
""")
    (scratch / "analysis_options.yaml").write_text(ANALYSIS_OPTIONS)
    toml = ['framework = "flutter"', "", "[contracts]", ""]
    for ns, src in contracts.items():
        toml += [f"[contracts.{ns}]", f'source = "{src}"', 'framework = "flutter"', ""]
    (scratch / "AxiomDeps.toml").write_text("\n".join(toml))
    (lib / "prelude.dart").write_text(PRELUDE)
    r = run(["flutter", "pub", "get"], scratch)
    if r.returncode:
        sys.exit(f"flutter pub get failed:\n{r.stdout}\n{r.stderr}")
    r = run(["dart", "run", "axiom_flutter_generator:generate", "--config", "AxiomDeps.toml",
             "--out", "axiom_generated", "--project-root", str(scratch)], scratch)
    if r.returncode:
        sys.exit(f"generator failed:\n{r.stdout}\n{r.stderr}")


def build_public_contracts(scratch, axiom):
    out = {}
    cdir = scratch / "contracts"
    cdir.mkdir(parents=True, exist_ok=True)
    for ns in PUBLIC_CONTRACTS:
        src = FLUTTER / "tool/docs_contracts" / ns
        dest = cdir / f"{ns}.axiom"
        r = run([axiom, "build", "main.acore", "--out", str(dest)], src)
        if r.returncode:
            sys.exit(f"axiom build {src} failed:\n{r.stdout}\n{r.stderr}")
        out[ns] = dest
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--public-docs", type=Path, help="AxiomCore docs/content/docs folder")
    ap.add_argument("--scratch", type=Path)
    ap.add_argument("--keep", action="store_true", help="print the scratch path, keep it")
    ap.add_argument("--axiom", default=shutil.which("axiom") or os.path.expanduser("~/bin/axiom"))
    args = ap.parse_args()

    scratch = args.scratch or Path(tempfile.mkdtemp(prefix="verify_docs_"))
    scratch.mkdir(parents=True, exist_ok=True)
    if (scratch / "lib").exists():
        # Reuse is fine; stale snippet files are overwritten or never imported.
        for f in (scratch / "lib").glob("s_*.dart"):
            f.write_text("")

    if args.public_docs:
        docs = [args.public_docs / p for p in PUBLIC_PAGES]
        contracts = build_public_contracts(scratch, args.axiom)
    else:
        docs = README_DOCS
        contracts = README_CONTRACTS
    make_package(scratch, contracts)

    # file name -> list of (doc, first doc line, first file line, line count, kind)
    mapping = {}
    count = 0
    for doc in docs:
        units = []  # [(start line, code)] lists; a continued block joins the last one
        for line, code, continued in extract_blocks(doc):
            if continued and units:
                units[-1].append((line, code))
            else:
                units.append([(line, code)])
        for unit in units:
            count += len(unit)
            name = f"s_{count:03d}_{re.sub(r'[^a-z0-9]+', '_', doc.stem.lower())}.dart"
            header = HEADER.format(src=doc, line=unit[0][0])
            code = "\n".join(c for _, c in unit)
            src, offset, kind = wrap(code)
            segs, fline = [], header.count("\n") + offset + 1
            for line, c in unit:
                n = c.count("\n") + 1
                segs.append((doc, line, fline, n, kind))
                fline += n
            (scratch / "lib" / name).write_text(header + src)
            mapping[name] = segs
    print(f"{count} dart blocks from {len(docs)} files; scratch {scratch}")

    r = run(["dart", "analyze", "--format=machine", "lib"], scratch)
    problems = 0
    for raw in (r.stdout + r.stderr).splitlines():
        parts = raw.split("|")
        if len(parts) < 8 or parts[0] not in ("ERROR", "WARNING"):
            continue
        sev, _, codename, file, lno, col = parts[:6]
        msg = "|".join(parts[7:])
        name = Path(file).name
        if name not in mapping:
            print(f"{sev} {file}:{lno}: {msg} [{codename}]")
            problems += 1
            continue
        segs = mapping[name]
        seg = next((s for s in segs if s[2] <= int(lno) < s[2] + s[3]), None)
        if seg is None:  # wrapper line: report at the block start
            seg = segs[0] if int(lno) < segs[0][2] else segs[-1]
        doc, start, fline, _, kind = seg
        doc_line = start + max(0, int(lno) - fline)
        rel = doc.relative_to(REPO) if doc.is_relative_to(REPO) else doc
        print(f"{sev} {rel}:{doc_line}:{col} ({kind} block at line {start - 1}): {msg} [{codename}]")
        problems += 1
    if problems:
        print(f"FAIL: {problems} problem(s)")
    else:
        print("OK: every dart block analyzes without errors or warnings")
    if not args.scratch and not args.keep:
        print(f"(scratch left at {scratch}; delete it when done)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
